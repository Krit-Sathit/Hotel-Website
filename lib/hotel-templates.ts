export function findMatchingTemplate(theme?: Partial<HotelTheme> | null): HotelWebsiteTemplate | undefined {
  if (!theme) return undefined;
  if (theme.template_id) {
    const byId = HOTEL_WEBSITE_TEMPLATES.find((t) => t.id === theme.template_id);
    if (byId) return byId;
  }
  return HOTEL_WEBSITE_TEMPLATES.find(
    (t) =>
      t.theme.primary_color.toLowerCase() === (theme.primary_color || '').toLowerCase() &&
      t.theme.accent_color.toLowerCase() === (theme.accent_color || '').toLowerCase() &&
      t.theme.font_family === theme.font_family &&
      t.theme.header_layout === theme.header_layout &&
      Boolean(t.theme.dark_mode) === Boolean(theme.dark_mode)
  );
}
